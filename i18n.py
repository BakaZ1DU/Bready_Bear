def display_account(name: str) -> str:
    """把默认账号名按界面语言显示；客户自定义名字原样保留。"""
    if LANG == "zh" or not name:
        return name
    src = str(name)
    if LANG == "en":
        src = src.replace("（主号）", " (Main)").replace("（备用）", " (Backup)")
        if src.startswith("账号"):
            src = "Account " + src[2:]
        return src
    if LANG == "ja":
        src = src.replace("（主号）", "（メイン）").replace("（备用）", "（予備）")
        if src.startswith("账号"):
            src = "アカウント" + src[2:]
        return src
    return name


def tr_runtime(text: str) -> str:
    """先精确翻译，再替换动态句子里常见的中文片段。"""
    out = tr(text)
    phrases = PHRASES_EN if LANG == "en" else (PHRASES_JA if LANG == "ja" else {})
    if not phrases:
        return out
    for src in sorted(phrases, key=len, reverse=True):
        if src in out:
            out = out.replace(src, phrases[src])
    return out



def apply_texts(root) -> None:
    """把已构建控件上的中文静态文本替换成当前语言；不碰输入框内容。"""
    if LANG == "zh":
        return
    for w in root.winfo_children():
        try:
            if isinstance(w, (tk.Label, tk.Button, tk.Checkbutton, tk.Radiobutton)):
                old = w.cget("text")
                lead = old[:len(old) - len(old.lstrip())]
                core = old.strip()
                new = tr_runtime(core)
                if new != core:
                    w.configure(text=lead + new)
            elif isinstance(w, ttk.Label):
                old = w.cget("text")
                new = tr(old)
                if new != old:
                    w.configure(text=new)
        except Exception:
            pass
        try:
            apply_texts(w)
        except Exception:
            pass
